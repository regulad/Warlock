//! Compiles Warlock's event manifest (`events.man`) into a resource of
//! `warlock.exe`, with the Windows SDK's `mc.exe` and `rc.exe`, and turns
//! the header `mc.exe` writes into the constants `src/events.rs` uses: the
//! provider's GUID and an event descriptor per event. The manifest is the
//! one source of both. (The diagnostics' release and DSN are
//! `warlock-diagnostics`'s, from its build script.)

use std::env;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=events.man");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("events.man");
    let sdk = sdk_bin().expect("the Windows SDK's x64 mc.exe and rc.exe weren't found: install the Windows SDK");
    run(Command::new(sdk.join("mc.exe")).arg("-h").arg(&out).arg("-r").arg(&out).arg(&manifest));
    // The .rc mc.exe writes names its binaries relative to itself.
    run(Command::new(sdk.join("rc.exe")).args(["/nologo", "/fo", "events.res", "events.rc"]).current_dir(&out));
    println!("cargo:rustc-link-arg-bins={}", out.join("events.res").display());
    let header = std::fs::read_to_string(out.join("events.h")).expect("mc.exe's header");
    std::fs::write(out.join("events.rs"), constants(&header)).unwrap();
}

fn run(command: &mut Command) {
    let output = command.output().unwrap_or_else(|e| panic!("running {command:?}: {e}"));
    if !output.status.success() {
        panic!(
            "{command:?} failed:\n{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
    }
}

/// The newest Windows SDK `bin\<version>\x64` with both tools: from a
/// developer prompt's environment, else the SDK's registered root.
fn sdk_bin() -> Option<PathBuf> {
    let has_tools = |d: &Path| d.join("mc.exe").is_file() && d.join("rc.exe").is_file();
    if let Some(dir) = env::var_os("WindowsSdkVerBinPath").map(|d| PathBuf::from(d).join("x64"))
        && has_tools(&dir)
    {
        return Some(dir);
    }
    let root = kits_root().unwrap_or_else(|| PathBuf::from(r"C:\Program Files (x86)\Windows Kits\10"));
    let mut found: Vec<(Vec<u32>, PathBuf)> = std::fs::read_dir(root.join("bin"))
        .ok()?
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().into_string().ok()?;
            let version = name.split('.').map(|p| p.parse().ok()).collect::<Option<Vec<u32>>>()?;
            let dir = e.path().join("x64");
            has_tools(&dir).then_some((version, dir))
        })
        .collect();
    found.sort();
    found.pop().map(|(_, dir)| dir)
}

/// `KitsRoot10` under `HKLM\SOFTWARE\Microsoft\Windows Kits\Installed Roots`.
fn kits_root() -> Option<PathBuf> {
    let output = Command::new("reg")
        .args(["query", r"HKLM\SOFTWARE\Microsoft\Windows Kits\Installed Roots", "/v", "KitsRoot10"])
        .output()
        .ok()?;
    let text = String::from_utf8_lossy(&output.stdout);
    let line = text.lines().find(|l| l.contains("KitsRoot10"))?;
    Some(PathBuf::from(line.split_once("REG_SZ")?.1.trim()))
}

/// Rust constants from mc.exe's header lines:
/// `... const GUID PROVIDER = {0x…, 0x…, 0x…, {0x…, …}};` and
/// `... const EVENT_DESCRIPTOR EVENT_ERROR = {id, version, channel, level, opcode, task, keyword};`.
fn constants(header: &str) -> String {
    let mut rust = String::from("// Generated by build.rs from mc.exe's header for events.man.\n");
    for line in header.lines() {
        let Some((decl, values)) = line.split_once(" = {") else { continue };
        let name = decl.rsplit(' ').next().unwrap();
        let values: Vec<&str> = values
            .trim_end_matches("};")
            .split(',')
            .map(|v| v.trim().trim_matches(['{', '}']).trim())
            .filter(|v| !v.is_empty())
            .collect();
        if decl.contains("const GUID ") {
            assert_eq!(values.len(), 11, "{line}");
            writeln!(
                rust,
                "pub const {name}: GUID = GUID {{ data1: {}, data2: {}, data3: {}, data4: [{}] }};",
                values[0],
                values[1],
                values[2],
                values[3..].join(", ")
            )
            .unwrap();
        } else if decl.contains("const EVENT_DESCRIPTOR ") {
            assert_eq!(values.len(), 7, "{line}");
            writeln!(
                rust,
                "pub const {name}: EVENT_DESCRIPTOR = EVENT_DESCRIPTOR {{ Id: {}, Version: {}, Channel: {}, Level: {}, \
                 Opcode: {}, Task: {}, Keyword: {} }};",
                values[0], values[1], values[2], values[3], values[4], values[5], values[6]
            )
            .unwrap();
        }
    }
    rust
}
